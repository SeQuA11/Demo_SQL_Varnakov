BEGIN;

DROP VIEW  IF EXISTS v_room_state_report;
DROP TABLE IF EXISTS cleaning_task, payment, app_user, role, stay, guest, room_status_log, room_status,
                     room, room_category, bed_type, comfort_class, floor CASCADE;

-- ---------------------------------------------------------------------
--  Справочники номерного фонда
-- ---------------------------------------------------------------------
CREATE TABLE floor (
    id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number SMALLINT NOT NULL UNIQUE CHECK (number > 0)
);
COMMENT ON TABLE floor IS 'Этажи гостиницы';

CREATE TABLE comfort_class (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);
COMMENT ON TABLE comfort_class IS 'Класс комфорта: Стандарт, Эконом, Бюджет, Бизнес, Студия, Люкс';

CREATE TABLE bed_type (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(50) NOT NULL UNIQUE,
    beds_min SMALLINT    NOT NULL CHECK (beds_min > 0),     -- минимум кроватей
    beds_max SMALLINT    NOT NULL,                          -- максимум кроватей
    CHECK (beds_max >= beds_min)
);
COMMENT ON TABLE bed_type IS 'Конфигурация кроватей';

CREATE TABLE room_category (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL UNIQUE,
    comfort_class_id INT      NOT NULL REFERENCES comfort_class (id),
    capacity         SMALLINT CHECK (capacity > 0),           -- NULL: не указана заказчиком
    rooms_count      SMALLINT NOT NULL DEFAULT 1 CHECK (rooms_count > 0),
    bed_type_id      INT      REFERENCES bed_type (id)         -- NULL: не указан заказчиком
);
COMMENT ON TABLE room_category IS 'Категории номеров';

CREATE TABLE room (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number      VARCHAR(10) NOT NULL UNIQUE,
    floor_id    INT NOT NULL REFERENCES floor (id),
    category_id INT NOT NULL REFERENCES room_category (id)
);
COMMENT ON TABLE room IS 'Номера';

-- ---------------------------------------------------------------------
--  Состояние номеров на дату
-- ---------------------------------------------------------------------
CREATE TABLE room_status (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);
COMMENT ON TABLE room_status IS 'Статусы номеров: Занят, Чистый, Грязный, Назначен к уборке';

CREATE TABLE room_status_log (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     INT  NOT NULL REFERENCES room (id),
    status_id   INT  NOT NULL REFERENCES room_status (id),
    status_date DATE NOT NULL,
    UNIQUE (room_id, status_date)
);
COMMENT ON TABLE room_status_log IS 'Журнал состояния номерного фонда на дату';

-- ---------------------------------------------------------------------
--  Гости и заселения
-- ---------------------------------------------------------------------
CREATE TABLE guest (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name  VARCHAR(50) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    patronymic VARCHAR(50)
);
COMMENT ON TABLE guest IS 'Гости (клиенты)';

CREATE TABLE stay (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id       INT  NOT NULL REFERENCES room (id),
    guest_id      INT  NOT NULL REFERENCES guest (id),
    check_in      DATE NOT NULL,
    check_out     DATE,                               -- NULL: дата выезда не известна
    is_checked_in BOOLEAN     NOT NULL DEFAULT TRUE,  -- FALSE: только бронь, гость ещё не заехал
    card_number   VARCHAR(20),
    card_active   BOOLEAN     NOT NULL DEFAULT FALSE, -- блокируется в 12:00 в день выезда
    CONSTRAINT stay_dates_chk CHECK (check_out IS NULL OR check_out >= check_in)
);
COMMENT ON TABLE stay IS 'Бронирования и заселения гостей в номера';
CREATE INDEX stay_room_idx  ON stay (room_id);
CREATE INDEX stay_guest_idx ON stay (guest_id);

-- ---------------------------------------------------------------------
--  Авторизация по ролям
-- ---------------------------------------------------------------------
CREATE TABLE role (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);
COMMENT ON TABLE role IS 'Роли пользователей ИС';

CREATE TABLE app_user (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name       VARCHAR(50)  NOT NULL,
    first_name      VARCHAR(50)  NOT NULL,
    patronymic      VARCHAR(50),
    login           VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,                 -- хранится только хеш пароля
    role_id         INT          NOT NULL REFERENCES role (id),
    is_blocked      BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_attempts SMALLINT     NOT NULL DEFAULT 0,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,     -- первый вход по выданному паролю
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON TABLE app_user IS 'Пользователи ИС (сотрудники)';

INSERT INTO role (name) VALUES ('Администратор'), ('Пользователь');

-- ---------------------------------------------------------------------
--  Оплата и уборка
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_id INT           NOT NULL REFERENCES stay (id),
    amount  NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    paid_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
COMMENT ON TABLE payment IS 'Оплаты проживания';

CREATE TABLE cleaning_task (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     INT     NOT NULL REFERENCES room (id),
    app_user_id INT     NOT NULL REFERENCES app_user (id),
    task_date   DATE    NOT NULL,
    is_done     BOOLEAN NOT NULL DEFAULT FALSE
);
COMMENT ON TABLE cleaning_task IS 'График уборки номеров';

-- ---------------------------------------------------------------------
--  Отчёт по состоянию номерного фонда (как в документе заказчика)
-- ---------------------------------------------------------------------
CREATE VIEW v_room_state_report AS
SELECT l.status_date                AS "На дату",
       f.number || ' этаж'          AS "Этаж",
       r.number                     AS "Номер",
       c.name                       AS "Категория",
       s.name                       AS "Статус",
       (SELECT min(st.check_out) FROM stay st
         WHERE st.room_id = r.id
           AND st.check_in <= l.status_date
           AND (st.check_out IS NULL OR st.check_out >= l.status_date)) AS "Дата выезда"
FROM room_status_log l
JOIN room          r ON r.id = l.room_id
JOIN floor         f ON f.id = r.floor_id
JOIN room_category c ON c.id = r.category_id
JOIN room_status   s ON s.id = l.status_id;

COMMIT;
